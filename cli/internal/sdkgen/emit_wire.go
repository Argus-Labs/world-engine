// genAliasPrefix marks an import as a generated (protoc-gen-go) package. Every gen import an emitted
// wire file carries is aliased with it, and nothing else in the file is, which is what lets a later read
// of that file tell the generated imports from the hand-written ones (see findOwnerGenPackage).
const genAliasPrefix = "pb"

// RenderGoWire emits the in-place wire layer for one source package: per message an exported `ToProto`
// and `FromProto` (struct ↔ the protoc-generated proto message) and the direct encoders `SizeWire`/
// `AppendWire` (wire bytes straight from the struct, see emit_wire_direct.go), and for each top-level
// type (command, event, component, system event) `MarshalWire`/`UnmarshalWire` (proto bytes), so it
// satisfies schema.Serializable. There is no codec struct, no registry, and no init() — the methods live
// on the type itself; nested types get no MarshalWire/UnmarshalWire, since they never cross the wire on
// their own. The hand structs stay plain Go (only their Name method); proto owns the encoding.
//
// The file lives in the type's own package, because Go requires a method's receiver type to be
// same-package. A type another module owns therefore cannot have methods here at all: its converters are
// free functions, and mirrored carries them (see wireMirrorFuncs).
//
// Everything the header needs is accumulated while the body is written, never derived from a second walk
// of the messages. That is the invariant this file is built around: an import is registered by the same
// call that writes the name requiring it, so the header is a report of what was emitted rather than a
// guess that has to happen to agree. Call Result.ResolveGen before this — every generated-package path
// is read off the messages, not recomputed here.
func RenderGoWire(msgs []Message, mirrored map[string]Message) (string, error) {
	if len(msgs) == 0 {
		return "", nil
	}
	if err := checkDirectEncodable(msgs, mirrored); err != nil {
		return "", err
	}
	// Every message in this group shares one Go package, so they share one owning gen package.
	g := newWireGen(msgs[0].GenImport)

	var body strings.Builder
	for _, m := range msgs {
		wireToProto(&body, g, m)
		wireFromProto(&body, g, m)
		// Commands, events, components and system events all get the same wire methods, so each satisfies
		// the one schema.Serializable interface. Nested types get only ToProto/FromProto — they are
		// carried inside their parent's proto.
		switch m.Kind {
		case KindCommand, KindEvent, KindComponent, KindSystemEvent:
			wireCodec(&body, g, m)
		}
		// Every message, nested included: a parent sizes and writes its nested fields through these.
		wireDirect(&body, g, m)
	}

	mirrorBody, err := renderMirrors(g, mirrored)
	if err != nil {
		return "", err
	}
	// After the body and the mirrors, which are what ask for helpers; before the imports, which the
	// helper bodies add to.
	helpers := renderHelpers(g)

	var b strings.Builder
	b.WriteString("// Code generated by world sdk generate. DO NOT EDIT.\n\n")
	// Hide this file from the generator that writes it (see WireBuildTag).
	fmt.Fprintf(&b, "//go:build !%s\n\n", WireBuildTag)
	fmt.Fprintf(&b, "package %s\n\n", msgs[0].PkgName)

	specs := g.importSpecs()
	// pkgAlias is a heuristic that can, rarely, give two packages the same alias when they share their
	// last two path segments — which would emit two imports under one identifier and a file that will not
	// compile. Catch it here rather than in somebody's build.
	if err := checkImportAliases(specs); err != nil {
		return "", err
	}
	all := mirrorBody + body.String() + helpers
	if err := checkNoRedeclaration(all); err != nil {
		return "", err
	}
	b.WriteString("import (\n")
	for _, spec := range specs {
		fmt.Fprintf(&b, "\t%s\n", spec)
	}
	b.WriteString(")\n\n")
	b.WriteString(all)

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("generated wire Go did not parse: %w\n%s", err, b.String())
	}
	if err := checkSymbolsResolve(string(out)); err != nil {
		return "", err
	}
	return string(out), nil
}

