// checkSymbolsResolve refuses generated code that qualifies a name with a package it never imports.
//
// This is the guard the generator was missing. [format.Source] only PARSES, so a wire file writing
// `proto.Marshal` with no proto import is perfectly valid syntax: it lands on disk, generation reports
// success, and the failure surfaces in somebody else's `go build` far from the generator that caused it.
// The refactor that introduced the accumulator dropped exactly that import, and every existing test
// still passed.
//
// Only qualifiers are checkable here. Go's parser resolves identifiers against the file's own
// declarations, and a wire file is one file in a package whose types are declared in its siblings — so a
// bare unresolved name is usually legitimate. A name in the X position of a selector is not: receivers,
// parameters and locals all resolve, which leaves package qualifiers and mistakes.
func checkSymbolsResolve(src string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, WireFileName, src, 0)
	if err != nil {
		return fmt.Errorf("generated wire Go did not parse: %w", err)
	}
	imported := map[string]bool{}
	for _, spec := range f.Imports {
		p, uerr := strconv.Unquote(spec.Path.Value)
		if uerr != nil {
			continue
		}
		if spec.Name != nil {
			imported[spec.Name.Name] = true
			continue
		}
		imported[path.Base(p)] = true
	}
	// The identifiers used as a package qualifier, by identity rather than by name — the same name can
	// appear both as a qualifier and as something declared in a sibling file.
	qualifiers := map[*ast.Ident]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				qualifiers[id] = true
			}
		}
		return true
	})

	missing := map[string]bool{}
	for _, id := range f.Unresolved {
		if !qualifiers[id] || goBuiltins[id.Name] || imported[id.Name] {
			continue
		}
		missing[id.Name] = true
	}
	if len(missing) == 0 {
		return nil
	}
	return fmt.Errorf("generated wire code qualifies names with %s but imports no such package — this is "+
		"a generator bug, please report it with the field types involved",
		strings.Join(slices.Sorted(maps.Keys(missing)), ", "))
}

// renderMirrors emits the converter pair for every mirrored type the body asked for, and for every
// mirrored type those converters in turn ask for.
//
// A fixed point rather than one pass: a mirrored converter can reference further mirrored types, and
// those are fields of no local message. Each is rendered into its own buffer and the buffers are
// concatenated in sorted key order, so the file's contents never depend on the order the types were
// discovered in. Terminates because the key set is finite and only grows.
func renderMirrors(g *wireGen, mirrored map[string]Message) (string, error) {
	bodies := map[string]string{}
	for {
		var pending []string
		for k := range g.mirrors {
			if _, done := bodies[k]; !done {
				pending = append(pending, k)
			}
		}
		if len(pending) == 0 {
			break
		}
		sort.Strings(pending)
		for _, k := range pending {
			mm, ok := mirrored[k]
			if !ok {
				return "", fmt.Errorf("wire code calls a converter for %s, but no mirrored message was "+
					"discovered for it; this is a generator bug, please report it with the field type", k)
			}
			var one strings.Builder
			wireMirrorFuncs(&one, g, mm) // may register further mirrors
			bodies[k] = one.String()
		}
	}
	var out strings.Builder
	for _, k := range slices.Sorted(maps.Keys(bodies)) {
		out.WriteString(bodies[k])
	}
	return out.String(), nil
}

// wireGen accumulates everything a wire file's header must contain, recorded as the body is written.
//
// This is the whole reason the type exists. An import is registered by the same call that writes the
// name needing it, and a mirrored converter is requested by the same call that emits a call to it, so
// the header and the body cannot disagree. What this replaces was four separate walks of the message
// set — for imports, for feature flags, for gen packages and for mirrored converters — which all had to
// agree with what the emitters actually wrote, with nothing enforcing it. Every disagreement shipped as
// generated code that failed to compile, far from the generator that produced it.
type wireGen struct {
	owner   string            // alias of this file's own gen package
	imports map[string]string // import path -> alias ("" when the import needs none)
	mirrors map[string]bool   // keys of mirrored types whose converters this file must declare
	helpers map[string]bool   // package-level helpers the direct encoders asked for (see renderHelpers)
}

func newWireGen(ownGenImport string) *wireGen {
	g := &wireGen{imports: map[string]string{}, mirrors: map[string]bool{}, helpers: map[string]bool{}}
	g.owner = g.gen(ownGenImport)
	return g
}

// need records a plain import (no alias) for a package the emitted code names directly.
func (g *wireGen) need(path string) {
	if _, ok := g.imports[path]; !ok {
		g.imports[path] = ""
	}
}

// spec records an already-rendered `alias "path"` import spec, as discovery produces for a source
// package whose type this file names.
func (g *wireGen) spec(s string) {
	if s == "" {
		return
	}
	alias, imp := parseImportSpec(s)
	if _, ok := g.imports[imp]; !ok {
		g.imports[imp] = alias
	}
}

// gen returns the alias for a generated (protoc-gen-go) package, recording its import. Repeated calls
// for one package return the same alias; a leaf-name clash with an already-recorded package gets a
// numeric suffix.
func (g *wireGen) gen(importPath string) string {
	if importPath == "" {
		return ""
	}
	if a, ok := g.imports[importPath]; ok && a != "" {
		return a
	}
	alias := genAlias(path.Base(importPath))
	used := map[string]bool{}
	for _, a := range g.imports {
		used[a] = true
	}
	base := alias
	for i := 1; used[alias]; i++ {
		alias = fmt.Sprintf("%s%d", base, i)
	}
	g.imports[importPath] = alias
	return alias
}

// hand returns how to write a referenced type in this file, recording the import that spelling needs.
func (g *wireGen) hand(r TypeRef) string {
	g.spec(r.Import)
	return r.GoType
}

// mirrorCall names a mirrored type's free-function converter for dir (ToProto, FromProto, SizeWire or
// AppendWire), recording both the import its Go type needs and the fact that this file must declare
// it. Asking for the call is what puts it on the list, so a body never calls a function nothing declared.
func (g *wireGen) mirrorCall(r TypeRef, dir string) string {
	g.spec(r.Import)
	g.mirrors[r.Key()] = true
	return r.ConvFunc(dir)
}

// importSpecs returns the import lines, sorted by path. [format.Source] normalises the block afterwards.
// scalar names a scalar's decode-side cast target and registers whatever import that spelling needs.
// A NAMED scalar declared in another package (cardinal.EntityID) is written qualified, so its import has
// to travel with it — the same rule g.hand follows for messages. Encode-side casts go to proto's own
// basic types and never qualify, so only the decode side routes through here.
func (g *wireGen) scalar(s *Scalar) string {
	for _, spec := range s.Imports {
		g.spec(spec)
	}
	return handGoType(s)
}

func (g *wireGen) importSpecs() []string {
	specs := make([]string, 0, len(g.imports))
	for imp, alias := range g.imports {
		if alias == "" {
			specs = append(specs, strconv.Quote(imp))
			continue
		}
		specs = append(specs, fmt.Sprintf("%s %q", alias, imp))
	}
	sort.Strings(specs)
	return specs
}

func checkNoRedeclaration(body string) error {
	seen := map[string]bool{}
	for line := range strings.SplitSeq(body, "\n") {
		if !strings.HasPrefix(line, "func ") {
			continue
		}
		rest := strings.TrimPrefix(line, "func ")
		if strings.HasPrefix(rest, "(") { // a method: its receiver type disambiguates it
			continue
		}
		name, _, ok := strings.Cut(rest, "(")
		if !ok || name == "" {
			continue
		}
		if seen[name] {
			return fmt.Errorf("generated wire code declares %s twice — two types resolved to one "+
				"converter name; this is a generator bug, please report it with the field types involved",
				name)
		}
		seen[name] = true
	}
	return nil
}

// checkImportAliases fails if two import specs claim the same identifier for different packages — a
// pkgAlias collision (two packages sharing their last two path segments) that would emit two imports
// with one alias and an uncompilable wire file. Each spec is `alias "path"` or `"path"`.
func checkImportAliases(specs []string) error {
	byAlias := map[string]string{}
	for _, spec := range specs {
		alias, imp := parseImportSpec(spec)
		if prev, ok := byAlias[alias]; ok && prev != imp {
			return fmt.Errorf("wire import alias %q is claimed by two packages (%s and %s) — the alias "+
				"scheme can't disambiguate them; rename one of the Go packages", alias, prev, imp)
		}
		byAlias[alias] = imp
	}
	return nil
}

// parseImportSpec splits `alias "path"` (or `"path"`) into its alias and import path.
func parseImportSpec(spec string) (string, string) {
	if before, after, found := strings.Cut(spec, " "); found {
		return before, strings.Trim(after, `"`)
	}
	p := strings.Trim(spec, `"`)
	return goPkgName(path.Base(p)), p
}

// genAlias names a generated proto package's import. The "pb" prefix keeps it out of the namespace real
// Go packages occupy: a wire file imports the source package and its generated counterpart together, and
// those share a leaf whenever the source path is a single segment ("net" and "<gen>/net"), which is most
// of the standard library. Prefixing the generated side means the two can never claim the same alias.
func genAlias(leaf string) string {
	return genAliasPrefix + goPkgName(leaf)
}

// wireCodec emits a message's bytes-level wire methods: MarshalWire (the encoded value as a fresh
// slice) and UnmarshalWire (proto bytes → a fresh value, returned as any). It is emitted identically
// for commands, events, and components, so each satisfies the single schema.Serializable interface —
// there is no codec struct and no registry. The command queue and the ECS column are generic over the
// concrete type and dispatch by type, never by a name lookup. UnmarshalWire returns any (not the
// concrete type) so it fits one non-generic interface; callers that know the static type assert the
// result back (e.g. decoded.(MoveCommand)).
func wireCodec(b *strings.Builder, g *wireGen, m Message) {
	g.need(protoPkg) // proto.Unmarshal, below

	// MarshalWire is derived from the direct encoders, not a second encoder: one allocation, and the
	// same bytes by construction. It keeps proto.Marshal's panic on invalid UTF-8 via SizeWire.
	fmt.Fprintf(b, "func (c %s) MarshalWire() []byte {\n", m.Name)
	b.WriteString("\treturn c.AppendWire(make([]byte, 0, c.SizeWire()))\n}\n\n")

	fmt.Fprintf(b, "func (c %s) UnmarshalWire(data []byte) (any, error) {\n", m.Name)
	fmt.Fprintf(b, "\tvar p %s.%s\n", g.owner, m.Name)
	b.WriteString("\tif err := proto.Unmarshal(data, &p); err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\treturn c.FromProto(&p), nil\n}\n\n")

	// Introspection reads this to describe registered types; the debug endpoint refuses to
	// finalize without it. Registered here so the import travels with the name that needs it.
	g.need(protoreflectPkg)
	fmt.Fprintf(b, "func (c %s) ProtoDescriptor() protoreflect.MessageDescriptor {\n", m.Name)
	fmt.Fprintf(b, "\treturn (&%s.%s{}).ProtoReflect().Descriptor()\n}\n\n", g.owner, m.Name)
}

// ToProto/FromProto are emitted exported so a command in one package can convert a nested type defined
// in another package of the same module (an unexported helper wouldn't be reachable across packages).
// Both are value receivers (FromProto returns a populated copy rather than filling in place): the type's
// method set must stay all-value because Name() must be a value receiver and Go discourages mixing value
// and pointer receivers. A nested field converts as c.Field = c.Field.FromProto(p.Field).

// pascalUnderscored PascalCases each underscore-separated segment: "lobby_component" -> "LobbyComponent".
//
// An EMPTY segment becomes "_" rather than being dropped, which keeps "a_b_c" and "a_b__c" distinct. A
// run of underscores is reachable: sanitizeToIdent maps every non-identifier rune to '_', so any path
// holding two adjacent ones ("my--game", "a.b-c") produces "__". Collapsing the two spellings would give
// two mirrored types one converter name, which checkNoRedeclaration refuses — loudly, but only after the
// collision. A single underscore is unaffected.
func pascalUnderscored(s string) string {
	var b strings.Builder
	for seg := range strings.SplitSeq(s, "_") {
		if seg == "" {
			b.WriteString("_")
			continue
		}
		b.WriteString(strings.ToUpper(seg[:1]))
		b.WriteString(seg[1:])
	}
	return b.String()
}

// wireMirrorFuncs emits the converters for a mirrored message: ToProto/FromProto and the direct
// encoders, all free functions. The parameter is named c so the same field emitters used for methods
// apply unchanged.
func wireMirrorFuncs(b *strings.Builder, g *wireGen, m Message) {
	gen := g.gen(m.GenImport)
	self := g.hand(m.Self)
	fmt.Fprintf(b, "func %s(c %s) *%s.%s {\n\tp := &%s.%s{}\n",
		m.Self.ConvFunc("ToProto"), self, gen, m.Name, gen, m.Name)
	for _, f := range m.Fields {
		wireToProtoField(b, g, f)
	}
	b.WriteString("\treturn p\n}\n\n")

	fmt.Fprintf(b, "func %s(p *%s.%s) %s {\n\tvar c %s\n\tif p == nil {\n\t\treturn c\n\t}\n",
		m.Self.ConvFunc("FromProto"), gen, m.Name, self, self)
	for _, f := range m.Fields {
		wireFromProtoField(b, g, f)
	}
	b.WriteString("\treturn c\n}\n\n")

	wireDirectMirror(b, g, m, self)
}

func wireToProto(b *strings.Builder, g *wireGen, m Message) {
	fmt.Fprintf(b, "func (c %s) ToProto() *%s.%s {\n\tp := &%s.%s{}\n", m.Name, g.owner, m.Name, g.owner, m.Name)
	for _, f := range m.Fields {
		wireToProtoField(b, g, f)
	}
	b.WriteString("\treturn p\n}\n\n")
}

func wireFromProto(b *strings.Builder, g *wireGen, m Message) {
	fmt.Fprintf(
		b,
		"func (c %s) FromProto(p *%s.%s) %s {\n\tif p == nil {\n\t\treturn c\n\t}\n",
		m.Name, g.owner, m.Name, m.Name,
	)
	for _, f := range m.Fields {
		wireFromProtoField(b, g, f)
	}
	b.WriteString("\treturn c\n}\n\n")
}

// timestampPkg and jsonPkg are named where they are used, so the import is registered by the same call
// that writes the reference. Nothing scans the messages a second time to work out whether they belong.
const (
	timestampPkg    = "google.golang.org/protobuf/types/known/timestamppb"
	protoPkg        = "google.golang.org/protobuf/proto"
	protoreflectPkg = "google.golang.org/protobuf/reflect/protoreflect"
	timePkg         = "time"
	timeGoType      = "time.Time" // the hand-written Go type a Timestamp maps to
)

// The immutable.Slice symbols the emitter writes as text. Nothing links this package's compile path
// to world-engine, so a rename there would surface only when a game builds its generated code. These
// are named once here so there is a single place to change, and so a test can bind each to the real
// symbol once go.mod carries a world-engine with pkg/immutable.
const (
	sliceCtor       = "SliceOf" // immutable.SliceOf(items...) — FromProto
	sliceIterMethod = "Values"  // Slice.Values() iter.Seq[T] — ToProto
)

func wireToProtoField(b *strings.Builder, g *wireGen, f Field) {
	if len(f.ArrayDims) > 0 {
		wireToProtoArray(b, g, f)
		return
	}
	switch f.Kind {
	case kindScalar:
		if f.Slice {
			// Slice[byte] -> bytes, read through Values like every other Slice. The element is already a
			// byte, so it appends as-is.
			fmt.Fprintf(b, "\tfor v := range c.%s.%s() {\n\t\tp.%s = append(p.%s, v)\n\t}\n",
				f.Name, sliceIterMethod, f.Name, f.Name)
			return
		}
		if f.Optional {
			// *T ↔ proto3 optional (also *T in Go). Deref-convert-readdress so a widening elem (e.g.
			// *int → *int64) still works; nil stays nil, preserving presence.
			fmt.Fprintf(b, "\tif c.%s != nil {\n\t\tv := %s(*c.%s)\n\t\tp.%s = &v\n\t}\n",
				f.Name, protoGoType(f.Scalar), f.Name, f.Name)
			return
		}
		fmt.Fprintf(b, "\tp.%s = %s(c.%s)\n", f.Name, protoGoType(f.Scalar), f.Name)
	case kindMessage:
		switch {
		case f.Timestamp && f.Pointer:
			g.need(timestampPkg)
			fmt.Fprintf(b, "\tif c.%s != nil {\n\t\tp.%s = timestamppb.New(*c.%s)\n\t}\n", f.Name, f.Name, f.Name)
		case f.Timestamp:
			g.need(timestampPkg)
			fmt.Fprintf(b, "\tp.%s = timestamppb.New(c.%s)\n", f.Name, f.Name)
		case f.Msg.Own.Mirrored() && f.Pointer:
			fmt.Fprintf(b, "\tif c.%s != nil {\n\t\tp.%s = %s(*c.%s)\n\t}\n",
				f.Name, f.Name, g.mirrorCall(f.Msg, "ToProto"), f.Name)
		case f.Msg.Own.Mirrored():
			fmt.Fprintf(b, "\tp.%s = %s(c.%s)\n", f.Name, g.mirrorCall(f.Msg, "ToProto"), f.Name)
		case f.Pointer:
			fmt.Fprintf(b, "\tif c.%s != nil {\n\t\tp.%s = c.%s.ToProto()\n\t}\n", f.Name, f.Name, f.Name)
		default:
			fmt.Fprintf(b, "\tp.%s = c.%s.ToProto()\n", f.Name, f.Name)
		}
	case kindRepeated:
		if f.Slice {
			fmt.Fprintf(
				b,
				"\tfor v := range c.%s.%s() {\n\t\tp.%s = append(p.%s, %s)\n\t}\n",
				f.Name, sliceIterMethod, f.Name, f.Name, elemToProto(g, f, "v"),
			)
			return
		}
		fmt.Fprintf(
			b,
			"\tfor i := range c.%s {\n\t\tp.%s = append(p.%s, %s)\n\t}\n",
			f.Name, f.Name, f.Name, elemToProto(g, f, fmt.Sprintf("c.%s[i]", f.Name)),
		)
	case kindMap:
		wireToProtoMapField(b, g, f)
	}
}

// sliceBufName names the collecting slice a Field.Slice field is rebuilt from, one per field so two Slice
// fields in one message never redeclare it (compare byteBufName).
func sliceBufName(field string) string { return "items" + field }

// elemGoType is the hand-written Go type of one repeated element — what the collecting slice for a
// Field.Slice field is made of.
func elemGoType(g *wireGen, f Field) string {
	switch {
	case f.Scalar != nil:
		return g.scalar(f.Scalar)
	case f.Timestamp:
		g.need(timePkg)
		return timeGoType
	default:
		return g.hand(f.Msg)
	}
}

// sliceOf returns the qualified SliceOf constructor for a Field.Slice field and records its import.
func (g *wireGen) sliceOf(f Field) string {
	g.spec(f.SliceImport)
	alias, _ := parseImportSpec(f.SliceImport)
	return alias + "." + sliceCtor
}

// -------------------------------------------------------------------------------------------------
// Fixed arrays
// -------------------------------------------------------------------------------------------------
// A fixed array is carried as one flat repeated field in row-major order (see classifyArray), so the
// decoder has to rebuild the indices from strides it computes here as constants.
//
// Decode is bounded by the array's own length, not the message's. Nothing on the wire carries the
// bound, so an over-long message is truncated rather than trusted, and a short one leaves the tail at
// its zero value — which is what lets the encoder stop at the last non-zero element.

// byteBufName is the local the multi-dimensional byte encoder accumulates into, for the field named
// field. Per field, not a shared constant: ToProto emits one of these per multi-dimensional byte array,
// so a message with two of them declared the same local twice ("no new variables on left side of :=").
// The prefix keeps it clear of a message field of the same name, since both are in scope here.
func byteBufName(field string) string { return "flat" + field }

// elemToProto is the expression converting one Go element, named by access, into its proto form.
// Shared by the repeated and fixed-array encoders, which differ only in the loop around it.
func elemToProto(g *wireGen, f Field, access string) string {
	switch {
	case f.Scalar != nil:
		return fmt.Sprintf("%s(%s)", protoGoType(f.Scalar), access)
	case f.Timestamp:
		g.need(timestampPkg)
		return fmt.Sprintf("timestamppb.New(%s)", access)
	case f.Msg.Own.Mirrored():
		return g.mirrorCall(f.Msg, "ToProto") + "(" + access + ")"
	default:
		return access + ".ToProto()"
	}
}

// arrayIndexExpr renders the index chain that maps a flat position to an element of a fixed array,
// e.g. "[i/8][i%8]" for [4][8]T. strides are the products of the dimensions to the right.
func arrayIndexExpr(dims []int64, pos string) string {
	var b strings.Builder
	for j := range dims {
		stride := int64(1)
		for _, d := range dims[j+1:] {
			stride *= d
		}
		switch {
		case j == 0 && stride == 1:
			fmt.Fprintf(&b, "[%s]", pos)
		case j == 0:
			fmt.Fprintf(&b, "[%s/%d]", pos, stride)
		case stride == 1:
			fmt.Fprintf(&b, "[%s%%%d]", pos, dims[j])
		default:
			fmt.Fprintf(&b, "[(%s/%d)%%%d]", pos, stride, dims[j])
		}
	}
	return b.String()
}

// arrayLoopHeader opens one `for` per dimension and returns the indexed access expression for the
// innermost element, e.g. "c.Shapes[i0][i1]".
func arrayLoopHeader(b *strings.Builder, f Field) string {
	access := "c." + f.Name
	for j := range f.ArrayDims {
		fmt.Fprintf(b, "%sfor i%d := range %s {\n", strings.Repeat("\t", j+1), j, access)
		access += fmt.Sprintf("[i%d]", j)
	}
	return access
}

func arrayLoopFooter(b *strings.Builder, f Field) {
	for j := range slices.Backward(f.ArrayDims) {
		fmt.Fprintf(b, "%s}\n", strings.Repeat("\t", j+1))
	}
}

// wireToProtoArray encodes a fixed array into its flat repeated (or bytes) proto field.
func wireToProtoArray(b *strings.Builder, g *wireGen, f Field) {
	if f.Kind == kindScalar { // a byte array, flattened to one bytes field
		if len(f.ArrayDims) == 1 {
			fmt.Fprintf(b, "\tp.%s = c.%s[:]\n", f.Name, f.Name)
			return
		}
		// Deeper than one dimension, so the innermost array is what slices to []byte; the loops walk
		// everything above it in the same row-major order the decoder rebuilds.
		fmt.Fprintf(b, "\t%s := make([]byte, 0, %d)\n", byteBufName(f.Name), f.ArrayCount())
		access := "c." + f.Name
		for j := range f.ArrayDims[:len(f.ArrayDims)-1] {
			fmt.Fprintf(b, "%sfor i%d := range %s {\n", strings.Repeat("\t", j+1), j, access)
			access += fmt.Sprintf("[i%d]", j)
		}
		fmt.Fprintf(b, "%s%s = append(%s, %s[:]...)\n",
			strings.Repeat("\t", len(f.ArrayDims)), byteBufName(f.Name), byteBufName(f.Name), access)
		for j := len(f.ArrayDims) - 2; j >= 0; j-- {
			fmt.Fprintf(b, "%s}\n", strings.Repeat("\t", j+1))
		}
		fmt.Fprintf(b, "\tp.%s = %s\n", f.Name, byteBufName(f.Name))
		return
	}
	indent := strings.Repeat("\t", len(f.ArrayDims)+1)
	access := arrayLoopHeader(b, f)
	fmt.Fprintf(b, "%sp.%s = append(p.%s, %s)\n", indent, f.Name, f.Name, elemToProto(g, f, access))
	arrayLoopFooter(b, f)
}

// wireFromProtoArray decodes the flat proto field back into the fixed array.
func wireFromProtoArray(b *strings.Builder, g *wireGen, f Field) {
	if f.Kind == kindScalar { // a byte array, flattened to one bytes field
		if len(f.ArrayDims) == 1 {
			fmt.Fprintf(b, "\tcopy(c.%s[:], p.%s)\n", f.Name, f.Name)
			return
		}
		idx := arrayIndexExpr(f.ArrayDims, "i")
		fmt.Fprintf(b, "\tfor i, v := range p.%s {\n\t\tif i >= %d {\n\t\t\tbreak\n\t\t}\n", f.Name, f.ArrayCount())
		fmt.Fprintf(b, "\t\tc.%s%s = v\n\t}\n", f.Name, idx)
		return
	}
	idx := arrayIndexExpr(f.ArrayDims, "i")
	fmt.Fprintf(b, "\tfor i, e := range p.%s {\n\t\tif i >= %d {\n\t\t\tbreak\n\t\t}\n", f.Name, f.ArrayCount())
	switch {
	case f.Scalar != nil:
		fmt.Fprintf(b, "\t\tc.%s%s = %s(e)\n", f.Name, idx, g.scalar(f.Scalar))
	case f.Timestamp:
		fmt.Fprintf(b, "\t\tc.%s%s = e.AsTime()\n", f.Name, idx)
	case f.Msg.Own.Mirrored():
		// Nobody generated this type, so it has no FromProto — the converter is a free function here.
		fmt.Fprintf(b, "\t\tc.%s%s = %s(e)\n", f.Name, idx, g.mirrorCall(f.Msg, "FromProto"))
	default:
		fmt.Fprintf(b, "\t\tvar v %s\n\t\tc.%s%s = v.FromProto(e)\n", g.hand(f.Msg), f.Name, idx)
	}
	b.WriteString("\t}\n")
}

// wireToProtoMapField encodes a Go map into its proto map. The three value shapes differ only in the
// proto type they land in and how one value converts, so the surrounding literal is written once.
func wireToProtoMapField(b *strings.Builder, g *wireGen, f Field) {
	pk := protoGoType(f.Key)

	var valType, conv string
	switch {
	case f.Timestamp:
		g.need(timestampPkg)
		valType, conv = "*timestamppb.Timestamp", "timestamppb.New(v)"
	case f.ValSc != nil:
		valType, conv = protoGoType(f.ValSc), protoGoType(f.ValSc)+"(v)"
	case f.Val.Own.Mirrored():
		// Nobody generated this type, so it has no ToProto of its own — the converter is a free function
		// in this package.
		valType = "*" + g.gen(f.Val.GenImport) + "." + f.Val.Name
		conv = g.mirrorCall(f.Val, "ToProto") + "(v)"
	default:
		// A map-value message may live in another package, so it is reached through its own gen import.
		valType, conv = "*"+g.gen(f.Val.GenImport)+"."+f.Val.Name, "v.ToProto()"
	}

	fmt.Fprintf(
		b,
		"\tif len(c.%s) > 0 {\n\t\tp.%s = make(map[%s]%s, len(c.%s))\n\t\tfor k, v := range c.%s {\n\t\t\tp.%s[%s(k)] = %s\n\t\t}\n\t}\n",
		f.Name,
		f.Name,
		pk,
		valType,
		f.Name,
		f.Name,
		f.Name,
		pk,
		conv,
	)
}

func wireFromProtoField(b *strings.Builder, g *wireGen, f Field) {
	if len(f.ArrayDims) > 0 {
		wireFromProtoArray(b, g, f)
		return
	}
	switch f.Kind {
	case kindScalar:
		if f.Slice {
			// bytes -> Slice[byte], guarded for the same reason as the repeated case above.
			fmt.Fprintf(b, "\tif len(p.%s) > 0 {\n\tc.%s = %s(p.%s...)\n\t}\n",
				f.Name, f.Name, g.sliceOf(f), f.Name)
			return
		}
		if f.Optional {
			fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tv := %s(*p.%s)\n\t\tc.%s = &v\n\t}\n",
				f.Name, g.scalar(f.Scalar), f.Name, f.Name)
			return
		}
		fmt.Fprintf(b, "\tc.%s = %s(p.%s)\n", f.Name, g.scalar(f.Scalar), f.Name)
	case kindMessage:
		switch {
		case f.Timestamp && f.Pointer:
			// nil Timestamp → leave the *time.Time nil; else deref AsTime into a fresh addressable var.
			fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tv := p.%s.AsTime()\n\t\tc.%s = &v\n\t}\n", f.Name, f.Name, f.Name)
		case f.Timestamp:
			// nil Timestamp → leave the zero time.Time.
			fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tc.%s = p.%s.AsTime()\n\t}\n", f.Name, f.Name, f.Name)
		case f.Msg.Own.Mirrored() && f.Pointer:
			fmt.Fprintf(
				b,
				"\tif p.%s != nil {\n\t\tv := %s(p.%s)\n\t\tc.%s = &v\n\t}\n",
				f.Name, g.mirrorCall(f.Msg, "FromProto"), f.Name, f.Name,
			)
		case f.Msg.Own.Mirrored():
			fmt.Fprintf(b, "\tc.%s = %s(p.%s)\n", f.Name, g.mirrorCall(f.Msg, "FromProto"), f.Name)
		case f.Pointer:
			fmt.Fprintf(
				b,
				"\tif p.%s != nil {\n\t\tvar v %s\n\t\tv = v.FromProto(p.%s)\n\t\tc.%s = &v\n\t}\n",
				f.Name,
				g.hand(f.Msg),
				f.Name,
				f.Name,
			)
		default:
			// value field: FromProto returns a populated copy; a nil p.Field yields the zero value.
			fmt.Fprintf(b, "\tc.%s = c.%s.FromProto(p.%s)\n", f.Name, f.Name, f.Name)
		}
	case kindRepeated:
		if f.Slice {
			// A Slice cannot be appended to in place, so the elements collect in a plain slice first and
			// the field is rebuilt from it in one call.
			//
			// Guarded, so an absent or empty repeated field leaves the zero value rather than building an
			// empty-but-allocated Slice. That is what makes a restored component compare equal to a fresh
			// one under reflect.DeepEqual (so require.Equal), and it skips an allocation per empty list on
			// every snapshot restore.
			buf := sliceBufName(f.Name)
			fmt.Fprintf(b, "\tif len(p.%s) > 0 {\n", f.Name)
			fmt.Fprintf(b, "\t%s := make([]%s, 0, len(p.%s))\n", buf, elemGoType(g, f), f.Name)
			wireFromProtoRepeated(b, g, f, buf)
			fmt.Fprintf(b, "\tc.%s = %s(%s...)\n", f.Name, g.sliceOf(f), buf)
			fmt.Fprintf(b, "\t}\n")
			return
		}
		wireFromProtoRepeated(b, g, f, "c."+f.Name)
	case kindMap:
		wireFromProtoMapField(b, g, f)
	}
}

// wireFromProtoRepeated appends every element of p.<field> to dst, converting each on the way in.
func wireFromProtoRepeated(b *strings.Builder, g *wireGen, f Field, dst string) {
	switch {
	case f.Scalar != nil:
		fmt.Fprintf(
			b,
			"\tfor _, x := range p.%s {\n\t\t%s = append(%s, %s(x))\n\t}\n",
			f.Name, dst, dst, g.scalar(f.Scalar),
		)
	case f.Timestamp:
		fmt.Fprintf(
			b,
			"\tfor _, e := range p.%s {\n\t\t%s = append(%s, e.AsTime())\n\t}\n",
			f.Name, dst, dst,
		)
	case f.Msg.Own.Mirrored():
		fmt.Fprintf(
			b,
			"\tfor _, e := range p.%s {\n\t\t%s = append(%s, %s(e))\n\t}\n",
			f.Name, dst, dst, g.mirrorCall(f.Msg, "FromProto"),
		)
	default:
		fmt.Fprintf(
			b,
			"\tfor _, e := range p.%s {\n\t\tvar v %s\n\t\tv = v.FromProto(e)\n\t\t%s = append(%s, v)\n\t}\n",
			f.Name, g.hand(f.Msg), dst, dst,
		)
	}
}

// wireFromProtoMapField decodes a proto map back into its Go map. As with encoding, the three value
// shapes share one literal; the message case needs a statement before the assignment, since FromProto
// is a method on the value being produced.
func wireFromProtoMapField(b *strings.Builder, g *wireGen, f Field) {
	hk := g.scalar(f.Key)

	var valType, prelude, conv string
	switch {
	case f.Timestamp:
		// The make() names the type literally, so the decode side needs `time` even though the encode
		// side does not.
		g.need(timePkg)
		valType, conv = timeGoType, "v.AsTime()"
	case f.ValSc != nil:
		valType, conv = g.scalar(f.ValSc), g.scalar(f.ValSc)+"(v)"
	case f.Val.Own.Mirrored():
		// Nobody generated this type, so it has no FromProto — the converter is a free function here.
		valType = g.hand(f.Val)
		conv = g.mirrorCall(f.Val, "FromProto") + "(v)"
	default:
		valType = g.hand(f.Val)
		prelude = "\t\t\tvar mv " + valType + "\n\t\t\tmv = mv.FromProto(v)\n"
		conv = "mv"
	}

	fmt.Fprintf(
		b,
		"\tif len(p.%s) > 0 {\n\t\tc.%s = make(map[%s]%s, len(p.%s))\n\t\tfor k, v := range p.%s {\n%s\t\t\tc.%s[%s(k)] = %s\n\t\t}\n\t}\n",
		f.Name,
		f.Name,
		hk,
		valType,
		f.Name,
		f.Name,
		prelude,
		f.Name,
		hk,
		conv,
	)
}

// protoGoType is the Go type of the protoc-generated field.
func protoGoType(s *Scalar) string {
	switch s.Proto {
	case "float":
		return "float32"
	case "double":
		return "float64"
	case "bytes":
		return "[]byte"
	default: // bool, int32/64, uint32/64, string
		return s.Proto
	}
}

// handGoType is the Go type of the hand-written field (the cast target on decode).
func handGoType(s *Scalar) string {
	if s.Family == "bytes" {
		return "[]byte"
	}
	return s.GoType
}
